    private val order = java.util.ArrayList<String>(512)

    @Synchronized
    private fun memo(key: String, calc: () -> String): String {
        cache[key]?.let { return it }
        val v = calc()
        cache[key] = v
        order.add(key)
        if (cache.size > CACHE_MAX) {
            // 丢掉最早缓存的一批，控制内存占用
            val drop = order.take(CACHE_MAX / 2)
            drop.forEach { cache.remove(it) }
            order.removeAll(drop.toSet())
        }
        return v
    }

    private fun ok(): Boolean {
        val u = useOpencc
        if (u != null) return u
        val v = runCatching {
            // 触发一次词典加载，失败就退回内嵌表
            com.github.houbb.opencc4j.util.ZhHkConverterUtil.toTraditional("测试")
            true
        }.getOrDefault(false)
        useOpencc = v
        NmLog.note("简繁转换引擎：${if (v) "opencc4j" else "内嵌表（opencc4j 不可用）"}")
        return v
    }

    /** 预热：后台线程提前加载词典，避免首次转换卡一下 */
    fun warmUp() {
        runCatching { ok() }
    }

    /**
     * 转成简体。
     * 优先 opencc4j（词组级，一简对多繁处理更准），失败退回内嵌表。
     */
    fun toSimple(s: String): String {
        if (s.isEmpty()) return s
        if (ok()) {
            return memo("s" + s) {
                runCatching {
                    com.github.houbb.opencc4j.util.ZhConverterUtil.toSimple(s)
                }.getOrNull() ?: simpleByTable(s)
            }
        }
        return simpleByTable(s)
    }

    /**
     * 转成香港繁体。
     * 用 opencc4j 的 ZhHkConverterUtil：先转标准繁体，再套香港用字习惯
     * （如「软件 / 軟件」「空调 / 冷氣」）。失败退回内嵌表。
     */
    fun toTrad(s: String): String {
        if (s.isEmpty()) return s
        if (ok()) {
            return memo("t" + s) {
                runCatching {
                    com.github.houbb.opencc4j.util.ZhHkConverterUtil.toTraditional(s)
                }.getOrNull() ?: tradByTable(s)
            }
        }
        return tradByTable(s)
    }

    // ---------- 内嵌表兜底 ----------

    private fun simpleByTable(s: String): String {
        if (s.isEmpty()) return s
        var out: StringBuilder? = null
        for (i in s.indices) {
            val c = s[i]
            val r = t2s[c]
            if (r == null) out?.append(c)
            else {
                if (out == null) {
                    out = StringBuilder(s.length)
                    out.append(s, 0, i)
                }
                out.append(r)
            }
        }
        return out?.toString() ?: s
    }

    private fun tradByTable(s: String): String {
        if (s.isEmpty()) return s
        var out: StringBuilder? = null
        for (i in s.indices) {
            val c = s[i]
            val r = s2t[c]
            if (r == null) out?.append(c)
            else {
                if (out == null) {
                    out = StringBuilder(s.length)
                    out.append(s, 0, i)
                }
                out.append(r)
            }
        }
        return out?.toString() ?: s
    }

    /** 按模式转换显示文本；不转换时原样返回 */
    fun display(s: String, mode: Int): String = when (mode) {
        TO_SIMPLE -> toSimple(s)
        TO_TRAD -> toTrad(s)
        else -> s
    }

    /**
     * 搜索用的关键词变体。
     * 只在「仅搜索统一」时返回另一种写法的关键词，用于把两种结果叠加。
     */
    fun searchVariant(kw: String, mode: Int): String? = when (mode) {
        SEARCH_ONLY -> {
            val s = toSimple(kw)
            val t = toTrad(kw)
            when {
                s != kw -> s
                t != kw -> t
                else -> null
            }
        }
        else -> null
    }
